"""Places people know, for My area: neighbourhood names to search by, and schools,
colleges and pharmacies to show near a home. All from the OpenStreetMap vector tiles
already in data/tiles (z14 `place` and `poi` layers), for every city.

    python3 tools/build_places.py            → src/js/data/places.js

Kept apart from geodata*.js on purpose: the engine never reads these, so rebuilding them
cannot move a forecast.
"""
import glob
import importlib
import json
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import mvt  # noqa: E402

ROOT = os.path.join(HERE, "..")
OUT = os.path.join(ROOT, "src", "js", "data", "places.js")
CITIES = {"nagpur": "spec_nagpur", "raleigh": "spec"}
PLACE_CLASSES = {"suburb": 0, "neighbourhood": 1, "quarter": 1, "village": 2, "hamlet": 3, "town": 0}
POI_CLASSES = {"school": "school", "college": "college", "pharmacy": "pharmacy"}


def tile_range(extent, z=14):
    def xy(lon, lat):
        n = 2 ** z
        x = int((lon + 180) / 360 * n)
        y = int((1 - math.asinh(math.tan(math.radians(lat))) / math.pi) / 2 * n)
        return x, y
    x0, y1 = xy(extent[0], extent[1])
    x1, y0 = xy(extent[2], extent[3])
    return x0, y0, x1, y1


def name_of(p):
    for k in ("name:en", "name_en", "name:latin", "name"):
        v = p.get(k)
        if v and str(v).strip():
            return str(v).strip()
    return None


def build(city, spec_name):
    spec = importlib.import_module(spec_name)
    w, s, e, n = spec.EXTENT
    x0, y0, x1, y1 = tile_range(spec.EXTENT)
    places, pois, seen_p, seen_poi = {}, [], set(), set()
    for path in glob.glob(os.path.join(ROOT, "data", "tiles", "14", "*", "*.pbf")):
        parts = os.path.normpath(path).split(os.sep)
        x, y = int(parts[-2]), int(parts[-1][:-4])
        if not (x0 <= x <= x1 and y0 <= y <= y1):
            continue
        layers = mvt.decode(open(path, "rb").read(), 14, x, y, layers={"place", "poi"})
        for f in layers.get("place", []):
            cls, nm = f["props"].get("class"), name_of(f["props"])
            if cls not in PLACE_CLASSES or not nm or not f["coords"]:
                continue
            lon, lat = f["coords"][0]
            if not (w <= lon <= e and s <= lat <= n):
                continue
            key = nm.lower()
            if key not in places or PLACE_CLASSES[cls] < PLACE_CLASSES[places[key][1]]:
                places[key] = [nm, cls, round(lon, 5), round(lat, 5)]
        for f in layers.get("poi", []):
            cls, nm = POI_CLASSES.get(f["props"].get("class")), name_of(f["props"])
            if not cls or not nm or not f["coords"]:
                continue
            lon, lat = f["coords"][0]
            key = (cls, nm.lower(), round(lon, 3), round(lat, 3))
            if key in seen_poi or not (w <= lon <= e and s <= lat <= n):
                continue
            seen_poi.add(key)
            pois.append([cls, nm, round(lon, 5), round(lat, 5)])
    out = {"places": sorted(places.values(), key=lambda p: p[0].lower()), "pois": sorted(pois, key=lambda p: (p[0], p[1].lower()))}
    counts = {c: sum(1 for p in pois if p[0] == c) for c in POI_CLASSES.values()}
    print(f"{city}: {len(out['places'])} places, {counts}")
    return out


def main():
    data = {city: build(city, spec) for city, spec in CITIES.items()}
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("// Generated by tools/build_places.py from the OpenStreetMap tiles (ODbL).\n")
        fh.write("// places: [name, class, lng, lat]; pois: [class, name, lng, lat].\n")
        fh.write("window.TWIN_PLACES = ")
        json.dump(data, fh, ensure_ascii=False, separators=(",", ":"))
        fh.write(";\n")
    print(f"wrote {OUT} ({os.path.getsize(OUT) / 1024:.0f} KB)")


if __name__ == "__main__":
    main()
